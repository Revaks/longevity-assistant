"""Приведение русского текста к основам — общее для индексации и запроса."""

import re

STOPWORDS = frozenset({
    # Вопросительные и указательные
    "что", "как", "какие", "какой", "какая", "какое", "сколько", "для", "это",
    "этот", "эта", "эти", "при", "надо", "нужно", "можно", "ли", "или", "не",
    "да", "нет", "очень", "вообще", "просто", "если", "чтобы", "почему",
    "зачем", "где", "когда", "мне", "я", "вы", "мы", "принимать", "делать",
    "сдавать", "посоветуй", "подскажи", "расскажи", "хочу", "хочется",
    # Предлоги: собраны из корпуса по частотности (топ помех)
    "в", "на", "с", "у", "по", "к", "о", "об", "от", "до", "из", "через",
    "над", "под", "между", "перед", "после", "без", "вместо", "кроме", "вдоль",
    # Союзы и частицы
    "и", "а", "но", "то", "же", "во", "ни", "вот",
    # Порядковое числительное (из "2-го", "1-го" и т.д.)
    "го",
})

# Окончания отсекаются от длинных к коротким: иначе «ами» никогда не сработает,
# потому что раньше сработает «и». Дательный падеж множественного числа (-ам, -ям)
# добавлен среди двухбуквенных, рядом с -ах/-ях.
_ENDINGS = (
    "иями", "ями", "ами", "ого", "его", "ому", "ему", "ыми", "ими",
    "ия", "ию", "ии", "ых", "их",
    "ая", "яя", "ое", "ее", "ые", "ие", "ой", "ей", "ом", "ем", "ах", "ях",
    "ам", "ям",  # дательный падеж множественного числа
    "ов", "ев", "ий", "ый", "ую", "юю", "ть", "ся",
    "а", "я", "о", "е", "ы", "и", "у", "ю", "й", "ь",
)

# Основа короче трёх символов перестаёт различать слова, но и порог 4 слишком груб:
# при нём «бегом» и «бега» дают разные основы, потому что отсечение не срабатывает.
_MIN_STEM = 3

# Исключения для слов с беглой гласной: собраны из реального корпуса.
# Беглая гласная требует морфологии, которую мы не тянем, поэтому используем словарь.
# Это узкий список слов, где беглая гласная реально встречается в текстах советов.
# Примеры: сон ~ сна (беглая 'о'), день ~ днем (беглая 'е').
_FLEETING_VOWEL_MAP = {
    "сна": "сон",  # сон ~ сна
    "сну": "сон",  # сон ~ сну
    "сном": "сон",  # сон ~ сном
    "сне": "сон",  # сон ~ сне
    "днем": "день",  # день ~ днем
}

_NON_WORD = re.compile(r"[^a-zа-я0-9]+")


def normalize(text: str) -> str:
    """Нижний регистр, ё как е, всё несловесное — пробел."""
    return _NON_WORD.sub(" ", text.lower().replace("ё", "е")).strip()


def tokenize(text: str) -> list[str]:
    return [t for t in normalize(text).split() if t]


def stem(token: str) -> str:
    """Грубое отсечение русских окончаний с защитой от схлопывания основы.

    Сначала проверяются исключения для слов с беглой гласной, затем применяется
    стандартное отсечение окончаний.
    """
    # Проверка исключений для беглой гласной (раньше отсечения окончаний)
    if token in _FLEETING_VOWEL_MAP:
        return _FLEETING_VOWEL_MAP[token]

    # Стандартное отсечение окончаний
    for ending in _ENDINGS:
        if token.endswith(ending) and len(token) - len(ending) >= _MIN_STEM:
            return token[: -len(ending)]
    return token


def analyze(text: str) -> list[str]:
    """Полный разбор: токены без стоп-слов, приведённые к основам."""
    return [stem(t) for t in tokenize(text) if t not in STOPWORDS]
